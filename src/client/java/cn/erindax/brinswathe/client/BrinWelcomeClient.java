package cn.erindax.brinswathe.client;

import cn.erindax.brinswathe.BrinWelcome;
import cn.erindax.brinswathe.network.BrinWelcomeS2CPacket;
import dev.doctor4t.wathe.api.Role;
import dev.doctor4t.wathe.client.gui.RoleAnnouncementTexts;
import dev.doctor4t.wathe.client.gui.RoleAnnouncementTexts.RoleAnnouncementText;
import dev.doctor4t.wathe.client.gui.RoundTextRenderer;
import net.fabricmc.api.EnvType;
import net.fabricmc.api.Environment;
import net.fabricmc.fabric.api.client.networking.v1.ClientPlayNetworking;
import org.agmas.harpymodloader.Harpymodloader;

@Environment(EnvType.CLIENT)
public final class BrinWelcomeClient {
    private BrinWelcomeClient() {
    }

    public static void init() {
        ClientPlayNetworking.registerGlobalReceiver(BrinWelcomeS2CPacket.TYPE, (payload, context) ->
            context.client().execute(() -> RoundTextRenderer.startWelcome(
                resolve(payload),
                payload.killers(),
                payload.targets()
            )));
    }

    private static RoleAnnouncementText resolve(BrinWelcomeS2CPacket payload) {
        switch (payload.kind()) {
            case BrinWelcome.KIND_KILLER -> {
                return RoleAnnouncementTexts.KILLER;
            }
            case BrinWelcome.KIND_VIGILANTE -> {
                return RoleAnnouncementTexts.VIGILANTE;
            }
            case BrinWelcome.KIND_CIVILIAN -> {
                return RoleAnnouncementTexts.CIVILIAN;
            }
            default -> {
            }
        }
        Role role = BrinRoleLabels.find(payload.roleId());
        if (role == null) return RoleAnnouncementTexts.CIVILIAN;
        RoleAnnouncementText text = Harpymodloader.autogeneratedAnnouncements.get(role);
        if (text == null) {
            Harpymodloader.refreshRoles();
            text = Harpymodloader.autogeneratedAnnouncements.get(role);
        }
        if (text != null) return text;
        return role.canUseKiller() ? RoleAnnouncementTexts.KILLER : RoleAnnouncementTexts.CIVILIAN;
    }
}
